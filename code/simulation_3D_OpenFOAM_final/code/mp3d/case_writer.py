"""Write an AdditiveFOAM case directory from a benchmark configuration.

A configuration is a YAML file; `extends: other.yaml` merges it over a parent,
so every case records only its differences from the canonical S0 setup.
"""
from __future__ import annotations

import copy
import json
from pathlib import Path

import yaml

from .materials import AFMaterial, constant_material, fit_steel, ss304_kim
from .meshspec import PATCH_FACES, block_mesh_dict, plate_axes, uniform_axis
from .schedule import ProcessSchedule

PATCHES = list(PATCH_FACES)

_HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by simulation_3D_OpenFOAM/code/mp3d/case_writer.py; do not edit.
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def _merge(base: dict, over: dict) -> dict:
    """Recursive merge; an explicitly empty dict in `over` replaces the base value."""
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and v and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def load_config(path) -> dict:
    path = Path(path)
    cfg = yaml.safe_load(path.read_text()) or {}
    parent = cfg.pop("extends", None)
    if parent:
        cfg = _merge(load_config(path.parent / parent), cfg)
    cfg.setdefault("config_file", path.name)
    return cfg


def build_material(cfg: dict) -> AFMaterial:
    m = cfg["material"]
    if m["type"] == "steel_fit":
        return fit_steel(m.get("liquid_k_multiplier", 1.0))
    if m["type"] == "ss304_kim":
        return ss304_kim(m.get("liquid_k_multiplier", 1.0))
    if m["type"] == "constant":
        return constant_material(m.get("name", "constant"), m["rho"], m["cp"], m["k"],
                                 Lf=m.get("Lf", 0.0), solidus=m.get("solidus", 1.0e6),
                                 liquidus=m.get("liquidus", 1.1e6),
                                 emissivity=m.get("emissivity", 0.0))
    raise ValueError(f"unknown material type {m['type']!r}")


def build_axes(cfg: dict):
    g, m = cfg["geometry"], cfg["mesh"]
    if m["type"] == "uniform":
        nx, ny, nz = m["n"]
        return uniform_axis(g["Lx"], nx), uniform_axis(g["Ly"], ny), uniform_axis(g["H"], nz)
    if m["type"] == "sections":
        # per-axis sections: [length, n, last/first ratio], or a graded section
        # {length, h_adjacent, q_max, small_end: first|last} sized by meshspec
        from .meshspec import Axis, Section, _geometric_section

        def sec(e):
            if isinstance(e, dict):
                return _geometric_section(float(e["length"]), float(e["h_adjacent"]),
                                          float(e.get("q_max", 1.2)), e.get("small_end", "first") == "first")
            L, n, r = e
            return Section(float(L), int(n), float(r))
        return tuple(Axis([sec(e) for e in m[a]]) for a in ("x", "y", "z"))
    if m["type"] == "plate_corridor":
        return plate_axes(Lx=g["Lx"], Ly=g["Ly"], H=g["H"], y_track=cfg["schedule"]["y0"],
                          h=m["h"], hz=m["hz"], x_fine_end=m["x_fine_end"],
                          y_half=m["y_half"], z_fine_depth=m["z_fine_depth"],
                          q_xy=m.get("q_xy", 1.1), q_z=m.get("q_z", 1.2))
    raise ValueError(f"unknown mesh type {m['type']!r}")


def _f(x) -> str:
    return repr(float(x))


def _vec(c) -> str:
    return "(" + " ".join(_f(v) for v in c) + ")"


def _write(case: Path, rel: str, cls: str, body: str) -> None:
    p = case / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(_HEADER.format(cls=cls, loc=str(Path(rel).parent), obj=Path(rel).name) + body)


def _patch_T(cfg: dict, name: str) -> str:
    b = cfg["boundary"]
    spec = dict(b["default"])
    spec.update((b.get("patches") or {}).get(name, {}))
    T0 = cfg["initial"]["T"]
    if spec["type"] == "mixedTemperature":
        body = (f"type mixedTemperature; h {_f(spec['h'])}; emissivity {_f(spec['emissivity'])};\n"
                f"        Tinf uniform {_f(b['T_inf'])}; value uniform {_f(T0)};")
    elif spec["type"] == "zeroGradient":
        body = "type zeroGradient;"
    else:
        raise ValueError(f"unsupported T boundary type {spec['type']!r}")
    return f"    {name}\n    {{\n        {body}\n    }}\n"


def patch_specs(cfg: dict) -> dict:
    """Resolved per-patch boundary parameters (used again in post-processing)."""
    b = cfg["boundary"]
    out = {}
    for name in PATCHES:
        spec = dict(b["default"])
        spec.update((b.get("patches") or {}).get(name, {}))
        out[name] = spec
    return out


def write_case(cfg: dict, case: Path) -> dict:
    """Write all dictionaries for `cfg` into `case`; return mesh metadata."""
    case = Path(case)
    mat = build_material(cfg)
    ax_x, ax_y, ax_z = build_axes(cfg)
    sched = ProcessSchedule.from_config(cfg)
    g, t, s, sol = cfg["geometry"], cfg["time"], cfg["source"], cfg["solver"]
    nprocs = int(cfg["run"]["nprocs"])

    _write(case, "system/blockMeshDict", "dictionary",
           block_mesh_dict(g["Lx"], g["Ly"], g["H"], ax_x, ax_y, ax_z))

    # T every snapshot; the iterated solid fraction less often, to check that it
    # stays on the thermoPath (post-processing otherwise uses alpha(T)).
    functions = f"""    snapshots
    {{
        type            writeObjects;
        libs            ("libutilityFunctionObjects.so");
        objects         (T);
        writeOption     anyWrite;
        writeControl    runTime;
        writeInterval   {_f(t['snapshot_interval'])};
    }}

    phaseSnapshots
    {{
        type            writeObjects;
        libs            ("libutilityFunctionObjects.so");
        objects         (alpha.solid);
        writeOption     anyWrite;
        writeControl    runTime;
        writeInterval   {_f(t.get('phase_snapshot_interval', 1.0))};
    }}
"""
    if cfg.get("outputs", {}).get("meltPoolDimensions", True) and mat.solidus < 1.0e5:
        functions += f"""
    meltPoolDimensions
    {{
        type            meltPoolDimensions;
        libs            ("libadditiveFoamFunctionObjects.so");
        isoValues       ({_f(mat.solidus)} {_f(mat.liquidus)});
        scanPathAngle   0;
    }}
"""
    pp = cfg.get("outputs", {}).get("patch_probes")
    if pp:
        # face values of a patch at given points, every time step (e.g. thermocouples)
        functions += f"""
    tcProbes
    {{
        type            patchProbes;
        libs            ("libsampling.so");
        patchName       {pp['patch']};
        fields          ({' '.join(pp.get('fields', ['T']))});
        probeLocations  ({' '.join(_vec(p) for p in pp['points'])});
        writeControl    timeStep;
        writeInterval   1;
    }}
"""
    _write(case, "system/controlDict", "dictionary", f"""application     additiveFoam;

startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {_f(t['t_end'])};
deltaT          {_f(t['dt'])};

writeControl    runTime;
writeInterval   {_f(t['full_write_interval'])};
purgeWrite      0;
writeFormat     binary;
writePrecision  12;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable no;

adjustTimeStep  no;

functions
{{
{functions}}}
""")

    _write(case, "system/fvSchemes", "dictionary", """ddtSchemes
{
    default         Euler;
}

gradSchemes
{
    default         Gauss linear;
}

divSchemes
{
    default         Gauss upwind;
}

laplacianSchemes
{
    default             Gauss linear corrected;
    laplacian(kappa,T)  Gauss harmonic corrected;
}

interpolationSchemes
{
    default         linear;
}

snGradSchemes
{
    default         corrected;
}
""")

    _write(case, "system/fvSolution", "dictionary", f"""solvers
{{
    "T.*"
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       {_f(sol['T_tolerance'])};
        relTol          0;
        minIter         1;
        maxIter         {int(sol['T_maxIter'])};
    }}

    "pcorr.*"
    {{
        solver          PCG;
        preconditioner  DIC;
        tolerance       1e-2;
        relTol          0;
    }}

    p_rgh
    {{
        solver          GAMG;
        tolerance       1e-06;
        relTol          0.01;
        smoother        DIC;
    }}

    p_rghFinal
    {{
        $p_rgh;
        relTol          0;
    }}
}}

// Thermal-only: nOuterCorrectors 0 disables the momentum-pressure loop.
PIMPLE
{{
    momentumPredictor           no;
    nOuterCorrectors            0;
    nCorrectors                 1;
    nNonOrthogonalCorrectors    0;
    pRefCell                    0;
    pRefValue                   0;

    nThermoCorrectors           {int(sol['nThermoCorrectors'])};
    thermoTolerance             {_f(sol['thermoTolerance'])};
    explicitSolve               false;
}}

relaxationFactors
{{
    equations
    {{
        ".*"            1;
    }}
}}
""")

    _write(case, "system/decomposeParDict", "dictionary",
           f"numberOfSubdomains  {nprocs};\n\nmethod              scotch;\n")

    _write(case, "constant/transportProperties", "dictionary", f"""// {mat.name}: {mat.notes}
// Polynomial<3> coefficients (a0 a1 a2): value = a0 + a1*T + a2*T^2.

solid
{{
    kappa   {_vec(mat.k_solid)};
    Cp      {_vec(mat.cp_solid)};
}}

liquid
{{
    kappa   {_vec(mat.k_liquid)};
    Cp      {_vec(mat.cp_liquid)};
}}

powder
{{
    kappa   {_vec(mat.k_solid)};
    Cp      {_vec(mat.cp_solid)};
}}

rho     [1 -3 0 0 0 0 0]    {_f(mat.rho)};
Lf      [0 2 -2 0 0 0 0]    {_f(mat.Lf)};

// Flow-only entries, unused because nOuterCorrectors = 0.
mu      [1 -1 -1 0 0 0 0]   0.006;
beta    [0 0 0 -1 0 0 0]    0;
DAS     [0 1 0 0 0 0 0]     1e-05;
dSigmadT    0;

emissivity  {_f(mat.emissivity)};

thermoPath
(
    ({_f(mat.solidus)} 1)
    ({_f(mat.liquidus)} 0)
);
""")

    radius = 2.0 * s["sigma"]          # secondMoment radius = 2 sigma
    _write(case, "constant/heatSourceDict", "dictionary", f"""// Planar Gaussian exp(-r^2/(2 sigma^2)), sigma = {_f(s['sigma'])} m
// (superGaussian k 2, secondMoment radius 2 sigma), one-sided exponential
// depth weight exp(-3|z|/depth); absorbed power = eta * scan-path power.
sources
{{
    arc
    {{
        path                scanPath;
        deltaT              {_f(s['beam_dt'])};
        hitPathIntervals    true;
        widthReference      D4Sigma;
        depthReference      constant;

        absorption
        {{
            model           constant;
            eta             {_f(s['eta'])};
        }}

        heatSource
        {{
            model           projected;
            depth           {_f(s['depth'])};
            tolerance       {_f(s['tolerance'])};
            nPoints         ({' '.join(str(int(v)) for v in s['nPoints'])});

            profile
            {{
                model       superGaussian;
                radius      ({_f(radius)} {_f(radius)});
                k           2;
                definition  secondMoment;
            }}

            projection
            {{
                model       exponential;
                nSlope      0;
                nIntercept  0;
            }}
        }}
    }}
}}

refinement
{{
    model   none;
}}
""")

    (case / "constant" / "scanPath").write_text(sched.scan_path_text(t["t_end"]))

    _write(case, "constant/g", "uniformDimensionedVectorField",
           "dimensions      [0 1 -2 0 0 0 0];\nvalue           (0 0 -9.81);\n")

    T0 = cfg["initial"]["T"]
    _write(case, "0/T", "volScalarField",
           "dimensions      [0 0 0 1 0 0 0];\n\n"
           f"internalField   uniform {_f(T0)};\n\nboundaryField\n{{\n"
           + "".join(_patch_T(cfg, p) for p in PATCHES) + "}\n")
    _write(case, "0/U", "volVectorField",
           "dimensions      [0 1 -1 0 0 0 0];\n\ninternalField   uniform (0 0 0);\n\n"
           "boundaryField\n{\n" + "".join(f"    {p}\n    {{\n        type noSlip;\n    }}\n" for p in PATCHES) + "}\n")
    _write(case, "0/p_rgh", "volScalarField",
           "dimensions      [0 2 -2 0 0 0 0];\n\ninternalField   uniform 0;\n\n"
           "boundaryField\n{\n" + "".join(
               f"    {p}\n    {{\n        type fixedFluxPressure;\n        rho rhok;\n        value uniform 0;\n    }}\n"
               for p in PATCHES) + "}\n")

    meta = {
        "n": [ax_x.n, ax_y.n, ax_z.n],
        "n_cells": ax_x.n * ax_y.n * ax_z.n,
        "sections": {name: [[sec.length, sec.n, sec.ratio] for sec in ax.sections]
                     for name, ax in (("x", ax_x), ("y", ax_y), ("z", ax_z))},
        "edges_x": ax_x.edges(0.0).tolist(),
        "edges_y": ax_y.edges(0.0).tolist(),
        "edges_z": ax_z.edges(-g["H"]).tolist(),
        "patches": patch_specs(cfg),
        "material": {k: v for k, v in mat.__dict__.items()},
    }
    (case / "mesh_meta.json").write_text(json.dumps(meta, indent=1))
    (case / "config_resolved.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    return meta
