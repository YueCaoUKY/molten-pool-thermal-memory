#!/usr/bin/env python3
"""The added simulations: the input channel that varies is changed, everything else follows design 4.

Design 4 varies the current at a fixed 0.5 mm/s. The two added designs vary the travel speed
instead, and both inputs together, keeping the same structure:

  speed   travel speed alternates between two nominal values, the current is fixed
  both    current and travel speed alternate together, in phase, so that the block with the
          higher current is also the slower one

Each record is 240 s of four 60 s blocks whose nominal values alternate large/small/large/small.
Inside a block the varying inputs take random 8-12 s steps around the nominal; the last 10 s of
every block holds every input exactly at the nominal, so blocks of the same kind end with an
identical input at different accumulated heat. The random speed offsets are made zero-mean over
each block's duration, so the bead is exactly 120 mm without rescaling the nominal values.

Levels come from source_estimate.py, chosen so that the two nominal operating points give the same
pool areas as design 4 (about 60 and 32 mm² in the calibrated estimate).

    python make_new_configs.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CFG = HERE.parent / "configs"
X0, BEAD, BLOCK, TAIL = 0.010, 0.120, 60.0, 10.0
SS304 = "material: {type: ss304_kim, liquid_k_multiplier: 5.0}"
COOLED = ["boundary:", "  patches:", "    bottom: {type: mixedTemperature, h: 700.0, emissivity: 0.0}"]
MAT_NAME = {"steel": "low-carbon steel", "ss304": "AISI 304L"}
SEED = 20260927

# (large-pool nominal, small-pool nominal) as (current A, speed mm/s); verified with source_estimate
LEVELS = {
    "steel": {"speed": ((82.9, 0.37), (82.9, 0.63)), "both": ((89.0, 0.47), (78.3, 0.53))},
    "ss304": {"speed": ((65.4, 0.37), (65.4, 0.63)), "both": ((70.5, 0.47), (61.6, 0.53))},
}


def blocks(rng, large, small, vary_current):
    """Four blocks, each ending with 10 s at the exact nominal current and speed."""
    segs = []
    for cur_nom, spd_nom in (large, small, large, small):
        durs = []
        t = 0.0
        while t < BLOCK - TAIL - 1e-9:
            d = min(float(rng.uniform(8.0, 12.0)), BLOCK - TAIL - t)
            durs.append(round(d, 2))
            t += d
        durs[-1] = round(BLOCK - TAIL - sum(durs[:-1]), 2)        # the block is exactly 50 s + tail
        off = rng.uniform(-0.06, 0.06, len(durs))                 # speed offsets, made zero-mean
        off -= np.average(off, weights=durs)
        for d, o in zip(durs, off):
            cur = round(cur_nom * (1 + float(rng.uniform(-0.04, 0.04))), 1) if vary_current else cur_nom
            segs.append((cur, spd_nom * (1 + float(o)), d))
        segs.append((cur_nom, spd_nom, TAIL))                     # the identical-input window
    return segs


def write(case, desc, note, segs, material, cooled):
    lines = [f"# {note}", "# Generated by node_identification/make_new_configs.py.",
             "extends: NI_base.yaml", f"case_id: {case}", f'description: "{desc}"']
    if material == "ss304":
        lines.append(SS304)
    if cooled:
        lines += COOLED
    lines += ["schedule:", "  segments:"]
    for i, (cur, spd, dur) in enumerate(segs):
        start = f"x_start: {X0}, " if i == 0 else ""
        lines.append(f"    - {{{start}current: {cur:g}, speed: {spd * 1e-3:.8g}, "
                     f"duration: {dur:g}, direction: 1}}")
    lines += ["time:", "  t_end: 240", ""]
    (CFG / f"{case}.yaml").write_text("\n".join(lines))
    bead = sum(s * 1e-3 * d for _, s, d in segs)
    return dict(case=case, material=material, description=desc, t_end=240.0, bead_mm=round(bead * 1e3, 3),
                segments=len(segs), cooled=cooled,
                current_range=[min(c for c, *_ in segs), max(c for c, *_ in segs)],
                speed_range=[round(min(s for _, s, _ in segs), 4), round(max(s for _, s, _ in segs), 4)])


def main():
    out = []
    for mat in ("steel", "ss304"):
        name = MAT_NAME[mat]
        for design in ("speed", "both"):
            large, small = LEVELS[mat][design]
            rng = np.random.default_rng(SEED + hash(mat + design) % 1000 if False else
                                        SEED + {"steel": 0, "ss304": 100}[mat] + {"speed": 0, "both": 10}[design])
            segs = blocks(rng, large, small, vary_current=(design == "both"))
            if design == "speed":
                d = (f"travel speed {large[1]:g}/{small[1]:g} mm/s in blocks of 60 s "
                     f"at a fixed {large[0]:g} A")
                note = "Only the travel speed varies; the current is fixed."
            else:
                d = (f"{large[0]:g} A at {large[1]:g} mm/s and {small[0]:g} A at {small[1]:g} mm/s "
                     f"in blocks of 60 s")
                note = "Current and travel speed vary together, in phase."
            for cooled in (False, True):
                plate = "cooled backing" if cooled else "free plate"
                case = f"PP_{mat}_{design}_{'cooled' if cooled else 'free'}"
                out.append(write(case, f"{d}, {plate} [{name}]",
                                 note + ("" if not cooled else
                                         " Water-cooled backing (bottom contact conductance 700 W/m²K)."),
                                 segs, mat, cooled))
    (HERE / "results" / "new_manifest.json").write_text(json.dumps(out, indent=1) + "\n")
    (HERE / "results" / "new_cases.txt").write_text("\n".join(m["case"] for m in out) + "\n")
    for m in out:
        print(f"{m['case']:26s} bead {m['bead_mm']:8.3f} mm  segments {m['segments']:3d}  "
              f"current {m['current_range'][0]:.1f}-{m['current_range'][1]:.1f} A  "
              f"speed {m['speed_range'][0]:.3f}-{m['speed_range'][1]:.3f} mm/s")


if __name__ == "__main__":
    main()
