#!/usr/bin/env python3
"""The paper's simulation set: five designs on two materials (2026-09-15).

Single straight bead, one direction, arc always on, pool present throughout.
Everything is held fixed except travel speed, the current schedule and, in
design 5, the heat loss through the bottom face:

  1 normal_var     1.5 mm/s, random current and speed steps   ordinary welding, varying input
  2 normal_const   1.5 mm/s, one level                        ordinary welding, constant input
  3 mid_var        1.0 mm/s, random steps                     the transition
  4 slow_cycles    0.5 mm/s, High/Low blocks of 60 s          strong heat memory; the last 10 s of
                                                              each block is exactly at its level, so
                                                              the two High ends and the two Low ends
                                                              have identical input
  5 slow_cooled    0.5 mm/s, the same schedule as 4           same process on a water-cooled backing

Currents come from source_estimate.py (calibrated per material to a finished
run), targeting a pool of about 60 mm² at the working level and 32 mm² at the
Low level. Bead length is 120 mm in every run, so the varying speeds are scaled
to keep it exact.

    python make_paper_configs.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CFG = HERE.parent / "configs"
X0 = 0.010
BEAD = 0.120
SS304 = "material: {type: ss304_kim, liquid_k_multiplier: 5.0}"
COOLED = ["boundary:", "  patches:", "    bottom: {type: mixedTemperature, h: 700.0, emissivity: 0.0}"]
MAT_NAME = {"steel": "low-carbon steel", "ss304": "AISI 304L"}


def write(case, desc, note, segs, t_end, material, cooled=False):
    lines = [f"# {note}", "# Generated by node_identification/make_paper_configs.py.",
             "extends: NI_base.yaml", f"case_id: {case}", f'description: "{desc}"']
    if material == "ss304":
        lines.append(SS304)
    if cooled:
        lines += COOLED
    lines += ["schedule:", "  segments:"]
    for i, (cur, spd, dur) in enumerate(segs):
        start = f"x_start: {X0}, " if i == 0 else ""
        lines.append(f"    - {{{start}current: {cur:g}, speed: {spd:g}, duration: {dur:g}, direction: 1}}")
    lines += ["time:", f"  t_end: {t_end:g}", ""]
    (CFG / f"{case}.yaml").write_text("\n".join(lines))
    length = sum(s * d for _, s, d in segs)
    return dict(case=case, material=material, description=desc, t_end=t_end, bead_mm=round(length * 1e3, 2),
                segments=len(segs), current_range=[min(c for c, *_ in segs), max(c for c, *_ in segs)])


def varying(rng, level, speed, duration, step=(10.0, 14.0), cur_frac=0.12, spd_frac=0.10):
    """Random current and speed steps; the speeds are then scaled so the bead is exactly 120 mm."""
    segs, t = [], 0.0
    while t < duration - 1e-9:
        d = min(float(rng.uniform(*step)), duration - t)
        segs.append([round(level * (1 + float(rng.uniform(-cur_frac, cur_frac))), 1),
                     speed * (1 + float(rng.uniform(-spd_frac, spd_frac))), round(d, 2)])
        t += d
    scale = BEAD / sum(s * d for _, s, d in segs)
    return [(c, round(s * scale, 8), d) for c, s, d in segs]


def cycles(rng, high, low, speed, block=60.0, exact_tail=10.0):
    """High/Low/High/Low blocks; random steps in the first 50 s, the exact level in the last 10 s."""
    segs = []
    for level in (high, low, high, low):
        t = 0.0
        while t < block - exact_tail - 1e-9:
            d = min(float(rng.uniform(8.0, 12.0)), block - exact_tail - t)
            segs.append((round(level * (1 + float(rng.uniform(-0.04, 0.04))), 1), speed, round(d, 2)))
            t += d
        segs.append((level, speed, exact_tail))
    return segs


def main():
    est = json.loads((HERE / "results" / "source_estimate.json").read_text())
    manifest = []
    for mat in ("steel", "ss304"):
        lv = est[mat]["levels"]
        i_norm = lv["normal"]["rows"][0]["current_A"]
        i_mid = lv["intermediate"]["rows"][0]["current_A"]
        i_high, i_low = (lv["extreme"]["rows"][0]["current_A"], lv["extreme"]["rows"][1]["current_A"])
        v_norm, v_mid, v_slow = 0.0015, 0.0010, 0.0005
        d_norm, d_mid, d_slow = BEAD / v_norm, BEAD / v_mid, BEAD / v_slow          # 80, 120, 240 s
        name = MAT_NAME[mat]
        rng = np.random.default_rng(abs(hash(mat)) % 10_000)
        manifest.append(write(
            f"PP_{mat}_1_normal_var", f"1 normal varying: {i_norm:g} A ±12 % at 1.5 mm/s, 120 mm bead [{name}]",
            "Ordinary welding speed with random current and speed steps.",
            varying(rng, i_norm, v_norm, d_norm), d_norm, mat))
        manifest.append(write(
            f"PP_{mat}_2_normal_const", f"2 normal constant: {i_norm:g} A at 1.5 mm/s, 120 mm bead [{name}]",
            "Ordinary welding speed at fixed parameters.",
            [(i_norm, v_norm, d_norm)], d_norm, mat))
        manifest.append(write(
            f"PP_{mat}_3_mid_var", f"3 intermediate varying: {i_mid:g} A ±12 % at 1.0 mm/s, 120 mm bead [{name}]",
            "Intermediate speed with random current and speed steps.",
            varying(rng, i_mid, v_mid, d_mid), d_mid, mat))
        cyc = cycles(rng, i_high, i_low, v_slow)
        manifest.append(write(
            f"PP_{mat}_4_slow_cycles",
            f"4 slow cycles: {i_high:g}/{i_low:g} A blocks of 60 s at 0.5 mm/s, free plate [{name}]",
            "Strong heat memory: High/Low/High/Low, each block ending with 10 s at the exact level.",
            cyc, d_slow, mat))
        manifest.append(write(
            f"PP_{mat}_5_slow_cooled",
            f"5 slow cycles, cooled backing: same schedule as design 4 [{name}]",
            "Same schedule as design 4 on a water-cooled backing (bottom contact conductance 700 W/m²K).",
            cyc, d_slow, mat, cooled=True))
    (HERE / "results" / "paper_manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    (HERE / "results" / "paper_cases.txt").write_text("\n".join(m["case"] for m in manifest) + "\n")
    for m in manifest:
        print(f"{m['case']:26s} {m['t_end']:6.0f} s  bead {m['bead_mm']:6.1f} mm  "
              f"current {m['current_range'][0]:.1f}-{m['current_range'][1]:.1f} A  segments {m['segments']}")


if __name__ == "__main__":
    main()
