#!/usr/bin/env python3
"""Second version of the speed-only pair: six 40 s blocks instead of four 60 s blocks.

The criterion, fixed before running: the identification interval must contain two visits to the
same input at different accumulated heat, otherwise the sensitivity of the pool equilibrium to the
hidden state is not identifiable. With six blocks the 50 % division at t = 120 s leaves blocks 1-3
for identification, which hold the large-pool nominal twice (30-40 s and 110-120 s) at different
workpiece temperature.

Everything else is unchanged from the first version: 82.9 A fixed, nominal speeds 0.37 and
0.63 mm/s, 240 s, 120 mm bead, and the free and cooled records share one input program.

    python make_v2_configs.py
"""
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
CFG = HERE.parent / "configs"
X0, BEAD, BLOCK, TAIL, NBLOCK = 0.010, 0.120, 40.0, 10.0, 6
COOLED = ["boundary:", "  patches:", "    bottom: {type: mixedTemperature, h: 700.0, emissivity: 0.0}"]
SEED = 20260928
CURRENT = 82.9
V_LARGE, V_SMALL = 0.37, 0.63          # mm/s; alternating with equal block length -> mean 0.50


def blocks(rng):
    """Six blocks; the last 10 s of each holds the exact nominal speed. The random offsets inside a
    block are made zero-mean over its duration, so the bead stays exactly 120 mm."""
    segs = []
    for i in range(NBLOCK):
        v_nom = V_LARGE if i % 2 == 0 else V_SMALL
        durs, t = [], 0.0
        while t < BLOCK - TAIL - 1e-9:
            d = min(float(rng.uniform(6.0, 10.0)), BLOCK - TAIL - t)
            durs.append(round(d, 2))
            t += d
        durs[-1] = round(BLOCK - TAIL - sum(durs[:-1]), 2)
        off = rng.uniform(-0.06, 0.06, len(durs))
        off -= np.average(off, weights=durs)
        for d, o in zip(durs, off):
            segs.append((CURRENT, v_nom * (1 + float(o)), d))
        segs.append((CURRENT, v_nom, TAIL))
    return segs


def write(case, desc, note, segs, cooled):
    lines = [f"# {note}", "# Generated by node_identification/make_v2_configs.py.",
             "extends: NI_base.yaml", f"case_id: {case}", f'description: "{desc}"']
    if cooled:
        lines += COOLED
    lines += ["schedule:", "  segments:"]
    for i, (cur, spd, dur) in enumerate(segs):
        start = f"x_start: {X0}, " if i == 0 else ""
        lines.append(f"    - {{{start}current: {cur:g}, speed: {spd * 1e-3:.8g}, "
                     f"duration: {dur:g}, direction: 1}}")
    lines += ["time:", "  t_end: 240", ""]
    (CFG / f"{case}.yaml").write_text("\n".join(lines))
    return sum(s * 1e-3 * d for _, s, d in segs)


def main():
    rng = np.random.default_rng(SEED)
    segs = blocks(rng)
    out = []
    for cooled in (False, True):
        plate = "cooled backing" if cooled else "free plate"
        case = f"PP_steel_speed_{'cooled' if cooled else 'free'}_v2"
        bead = write(case,
                     f"travel speed {V_LARGE:g}/{V_SMALL:g} mm/s in six blocks of 40 s at a fixed "
                     f"{CURRENT:g} A, {plate} [low-carbon steel]",
                     "Only the travel speed varies; six blocks so that the first half of the record "
                     "holds the large-pool nominal twice." +
                     (" Water-cooled backing (bottom contact conductance 700 W/m²K)." if cooled else ""),
                     segs, cooled)
        out.append(dict(case=case, bead_mm=round(bead * 1e3, 3), segments=len(segs), cooled=cooled))
    (HERE / "results" / "v2_cases.txt").write_text("\n".join(m["case"] for m in out) + "\n")
    # the constant-speed windows and what the 50 % division contains
    t = x = 0.0
    print(f"{'窗口 s':>14s} {'速度 mm/s':>10s} {'x mm':>7s}")
    for cur, spd, dur in segs:
        t0 = t; t += dur; x += spd * 1e-3 * dur
        if abs(dur - TAIL) < 1e-9:
            side = "训练段" if t <= 120.0 + 1e-9 else "留出段"
            kind = "大熔池" if abs(spd - V_LARGE) < 1e-9 else "小熔池"
            print(f"{f'{t0:.0f}-{t:.0f}':>14s} {spd:10.3f} {x * 1e3:7.1f}   {kind}  {side}")
    for m in out:
        print(f"{m['case']:30s} 焊道 {m['bead_mm']:.3f} mm  段数 {m['segments']}")


if __name__ == "__main__":
    main()
