#!/usr/bin/env python3
"""Second version of the 304L speed-only pair: six 40 s blocks, matching the steel pair.

Same criterion as make_v2_configs.py: the identification interval must hold the large-pool nominal
twice, at different accumulated heat. Only the material and the fixed current differ from the steel
pair, and the free and cooled records share one input program. The random offsets come from their
own draw, as the first version of this pair did.

    python make_v2_ss304_configs.py
"""
import numpy as np

import make_v2_configs as M

M.CURRENT = 65.4                                   # AISI 304L; the nominal speeds are unchanged
MATERIAL = ["material: {type: ss304_kim, liquid_k_multiplier: 5.0}"]


def write(case, desc, note, segs, cooled):
    lines = [f"# {note}", "# Generated by node_identification/make_v2_ss304_configs.py.",
             "extends: NI_base.yaml", f"case_id: {case}", f'description: "{desc}"'] + MATERIAL
    if cooled:
        lines += M.COOLED
    lines += ["schedule:", "  segments:"]
    for i, (cur, spd, dur) in enumerate(segs):
        start = f"x_start: {M.X0}, " if i == 0 else ""
        lines.append(f"    - {{{start}current: {cur:g}, speed: {spd * 1e-3:.8g}, "
                     f"duration: {dur:g}, direction: 1}}")
    lines += ["time:", "  t_end: 240", ""]
    (M.CFG / f"{case}.yaml").write_text("\n".join(lines))
    return sum(s * 1e-3 * d for _, s, d in segs)


def main():
    segs = M.blocks(np.random.default_rng(20260929))
    for cooled in (False, True):
        plate = "cooled backing" if cooled else "free plate"
        case = f"PP_ss304_speed_{'cooled' if cooled else 'free'}_v2"
        bead = write(case,
                     f"travel speed {M.V_LARGE:g}/{M.V_SMALL:g} mm/s in six blocks of 40 s at a "
                     f"fixed {M.CURRENT:g} A, {plate} [AISI 304L]",
                     "Only the travel speed varies; six blocks so that the first half of the record "
                     "holds the large-pool nominal twice." +
                     (" Water-cooled backing (bottom contact conductance 700 W/m²K)." if cooled else ""),
                     segs, cooled)
        print(f"{case:30s} 焊道 {bead * 1e3:.3f} mm  段数 {len(segs)}")
    t = 0.0
    print(f"\n{'窗口 s':>12s} {'速度 mm/s':>10s}  {'':>6s}")
    for cur, spd, dur in segs:
        t0 = t; t += dur
        if abs(dur - M.TAIL) < 1e-9:
            print(f"{f'{t0:.0f}-{t:.0f}':>12s} {spd:10.3f}  "
                  f"{'大熔池' if abs(spd - M.V_LARGE) < 1e-9 else '小熔池'} "
                  f"{'训练段' if t <= 120.0 + 1e-9 else '留出段'}")


if __name__ == "__main__":
    main()
